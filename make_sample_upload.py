import pandas as pd
src = pd.read_csv("data/hupa/HUPA-UCM Diabetes Dataset/Preprocessed/HUPA0016P.csv",
                  sep=None, engine="python", parse_dates=["time"])
# Mimic a LibreView export: title line, its column names, 15-minute readings
libre = src.iloc[::3][["time", "glucose"]].rename(
    columns={"time": "Device Timestamp", "glucose": "Historic Glucose mg/dL"})
with open("data/sample_libre_export.csv", "w") as f:
    f.write("Patient report,Generated by test\n")
    libre.to_csv(f, index=False)
print("Wrote data/sample_libre_export.csv")